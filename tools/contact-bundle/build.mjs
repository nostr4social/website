// Builds the three files /contact/ loads, and records their hashes.
//
//   npm run build:contact
//
// The two vendor files are minified — nobody reads a minified dependency, so
// the hash in _data/assets.yml and the pinned version in package.json are what
// a reviewer checks. contact.js is NOT minified: it is our code, and it is
// meant to be read with view-source.

import { build } from 'esbuild'
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')

// Read the installed version from disk: several packages do not export their
// own package.json, so `require('pkg/package.json')` is not dependable.
const version = async (name) =>
  JSON.parse(await readFile(resolve(root, 'node_modules', name, 'package.json'), 'utf8')).version

const NOSTR_TOOLS = await version('nostr-tools')
const UQR = await version('uqr')

export const targets = {
  nostr_tools: {
    entry: 'tools/contact-bundle/vendor-nostr-tools.entry.js',
    out: `assets/js/vendor/nostr-tools/nostr-tools-${NOSTR_TOOLS}.esm.min.js`,
    minify: true,
  },
  uqr: {
    entry: 'tools/contact-bundle/vendor-uqr.entry.js',
    out: `assets/js/vendor/uqr/uqr-${UQR}.esm.min.js`,
    minify: true,
  },
  app: {
    entry: 'assets/js/contact/src/app.js',
    out: 'assets/js/contact/contact.js',
    minify: false,
    // Our own modules are bundled; the vendor files stay separate imports so
    // they can be cached, hashed and reviewed on their own.
    external: ['/assets/js/vendor/*'],
  },
}

const sri = (bytes) => 'sha384-' + createHash('sha384').update(bytes).digest('base64')

export async function buildAll({ write = true } = {}) {
  const out = {}
  for (const [name, t] of Object.entries(targets)) {
    const result = await build({
      entryPoints: [resolve(root, t.entry)],
      outfile: resolve(root, t.out),
      bundle: true,
      format: 'esm',
      target: 'es2022',
      platform: 'browser',
      minify: t.minify,
      external: t.external ?? [],
      legalComments: 'none',
      write,
      logLevel: 'warning',
    })
    const bytes = write
      ? await readFile(resolve(root, t.out))
      : Buffer.from(result.outputFiles[0].contents)
    out[name] = { path: '/' + t.out, integrity: sri(bytes), size: bytes.length, bytes }
  }
  return out
}

function toYaml(assets) {
  const lines = [
    '# Generated by tools/contact-bundle/build.mjs. Do not edit by hand.',
    '#',
    '# `npm run check:contact` rebuilds from the pinned sources and fails if any',
    '# of these hashes moved, so the committed files cannot drift from the code.',
    'contact:',
  ]
  for (const [name, a] of Object.entries(assets)) {
    lines.push(`  ${name}:`)
    lines.push(`    path: ${a.path}`)
    lines.push(`    integrity: "${a.integrity}"`)
  }
  return lines.join('\n') + '\n'
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const assets = await buildAll()
  await writeFile(resolve(root, '_data/assets.yml'), toYaml(assets))
  for (const [name, a] of Object.entries(assets)) {
    console.log(`${name.padEnd(12)} ${String(a.size).padStart(7)} B  ${a.path}`)
  }
  console.log('\nwrote _data/assets.yml')
}

export { toYaml }
